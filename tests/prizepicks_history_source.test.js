'use strict';
const assert=require('node:assert/strict');
const {verifySourcePayload,buildHistoryAudit}=require('../scripts/prizepicks_history_source');
const {historyEvidence}=require('../scripts/prizepicks_history_evidence');
const now=Date.parse('2026-11-03T20:00:00Z');
const record={providerPlayerId:'p1',playerId:'p1',league:'NBA',market:'Points',period:'Full game',source:'independent',independentlyVerified:true,games:Array.from({length:15},(_,i)=>({eventId:'e'+i,playedAt:'2026-10-'+String(i+1).padStart(2,'0')+'T00:00:00Z',verified:true,value:i+10}))};
const payload={schema_version:1,status:'VERIFIED_GAME_LOGS',source:'independent',generated_at:'2026-11-03T18:00:00Z',records:[record]};
assert.equal(verifySourcePayload({},now).status,'UNAVAILABLE');
assert.equal(verifySourcePayload(payload,now).status,'VERIFIED_HISTORY_INPUT');
assert.equal(verifySourcePayload({...payload,generated_at:'2020-01-01T00:00:00Z'},now).status,'UNAVAILABLE');
assert.equal(verifySourcePayload({...payload,generated_at:'2026-11-04T18:00:00Z'},now).status,'UNAVAILABLE');
assert.equal(verifySourcePayload({...payload,records:[{...record,source:'different'}]},now).status,'UNAVAILABLE');
assert.equal(verifySourcePayload({...payload,records:[{...record,playerId:'wrong'}]},now).status,'UNAVAILABLE');
const feed={status:'RAW_LINES_ONLY',lines:[{id:'x',league:'NBA',player:'A',player_id:'p1',market:'Points',period:'Full game',line:15.5}]};
const audit=buildHistoryAudit(feed,payload,now);
assert.equal(audit.coverage.matched,1);assert.equal(audit.rows[0].betEligible,false);
assert.equal(buildHistoryAudit(feed,{...payload,generated_at:'2020-01-01T00:00:00Z'},now).status,'UNAVAILABLE');
const evidence=historyEvidence(record,15.5,now);
assert.equal(evidence.last5.sample,5);assert.equal(evidence.last10.sample,10);assert.equal(evidence.last15.sample,15);
assert.equal(evidence.last5.mean,22);assert.equal(evidence.last10.mean,19.5);
assert.equal(historyEvidence({...record,games:[...record.games,{...record.games[0]}]},15.5,now).status,'UNAVAILABLE');
assert.equal(historyEvidence({...record,games:[...record.games.slice(0,14),{...record.games[14],playedAt:'2026-11-05T00:00:00Z'}]},15.5,now).status,'UNAVAILABLE');
assert.equal(historyEvidence({...record,games:[...record.games.slice(0,14),{...record.games[14],verified:false}]},15.5,now).status,'UNAVAILABLE');
console.log('PrizePicks temporal provenance and chronological windows tests passed');
