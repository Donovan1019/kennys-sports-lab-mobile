'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const workflow=fs.readFileSync('.github/workflows/nfl-real-player-stats-ingestion.yml','utf8');
assert.match(workflow,/concurrency:\s*\n\s*group: nfl-history-publish/);
assert.match(workflow,/cancel-in-progress: false/);
assert.match(workflow,/jobs:\s*\n\s*ingest:[\s\S]*?permissions:\s*\n\s*contents: write/);
assert.doesNotMatch(workflow,/contents:\s*\$\{\{/);
assert.match(workflow,/git fetch origin main/);
assert.match(workflow,/git checkout -B main origin\/main/);
assert.match(workflow,/git push origin HEAD:main/);
assert.match(workflow,/independentlyVerified/);
const prizepicks=fs.readFileSync('.github/workflows/prizepicks-ingest.yml','utf8');
assert.ok(prizepicks.includes('    permissions:\n      contents: write'));
assert.ok(!prizepicks.includes('contents: ${{'));
assert.ok(prizepicks.includes('git show origin/main:feed/nfl_player_stats.json'));
assert.ok(prizepicks.includes('PRIZEPICKS_NFL_ARCHIVE_PATH: /tmp/prizepicks-nfl-player-stats.json'));
assert.ok(prizepicks.includes('git checkout -B main origin/main'));
console.log('NFL and PrizePicks audited publishing safety tests passed');
