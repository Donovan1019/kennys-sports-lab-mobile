'use strict';
const assert=require('node:assert/strict');
const {bridgeNflverseArchive}=require('../scripts/prizepicks_nflverse_bridge');
const now=Date.parse('2026-11-03T20:00:00Z');
const games=Array.from({length:15},(_,i)=>({eventId:'nfl-'+i,playedAt:'2026-10-'+String(i+1).padStart(2,'0')+'T00:00:00Z',verified:true,values:{'Receiving yards':i+20}}));
const archive={source:'nflverse-stats-player-week',independentlyVerified:true,fetched_at:'2026-11-03T19:00:00Z',players:[{player_id:'nfl-123',games}]};
const good=bridgeNflverseArchive(archive,now);
assert.equal(good.status,'VERIFIED_GAME_LOGS');
assert.equal(good.records.length,1);
assert.equal(good.records[0].games.length,15);
assert.equal(bridgeNflverseArchive({...archive,fetched_at:'2026-10-01T00:00:00Z'},now).status,'UNAVAILABLE');
assert.equal(bridgeNflverseArchive({...archive,players:[{name:'Unknown',games}]},now).status,'UNAVAILABLE');
assert.equal(bridgeNflverseArchive({...archive,players:[{player_id:'nfl-123',games:games.map(g=>({...g,playedAt:undefined}))}]},now).status,'UNAVAILABLE');
assert.equal(bridgeNflverseArchive({...archive,players:[{player_id:'nfl-123',games:[...games.slice(1),games[1]]}]},now).status,'UNAVAILABLE');
const negativeGames=games.map((g,i)=>({...g,values:{'Rushing yards':i===0?-7:i+1}}));
const negative=bridgeNflverseArchive({...archive,players:[{player_id:'nfl-123',games:negativeGames}]},now);
assert.equal(negative.status,'VERIFIED_GAME_LOGS');
assert.equal(negative.records.find(r=>r.market==='Rushing yards').games[0].value,-7);
const negativeReceptions=games.map((g,i)=>({...g,values:{Receptions:i===0?-1:i+1}}));
assert.equal(bridgeNflverseArchive({...archive,players:[{player_id:'nfl-123',games:negativeReceptions}]},now).status,'UNAVAILABLE');
const sparse=games.map((g,i)=>({...g,values:{'Receiving yards':i+20,...(i<5?{'Passing yards':i+10}:{})}}));
const sparseResult=bridgeNflverseArchive({...archive,players:[{player_id:'nfl-123',games:sparse}]},now);
assert.equal(sparseResult.status,'VERIFIED_GAME_LOGS');
assert.equal(sparseResult.records.length,1);
assert.equal(sparseResult.records[0].market,'Receiving yards');
const mixed=games.map((g,i)=>({...g,values:i===0?{'Receiving yards':undefined}:{'Receiving yards':i+20}}));
assert.equal(bridgeNflverseArchive({...archive,players:[{player_id:'nfl-123',games:mixed}]},now).status,'UNAVAILABLE');
const malformed=games.map((g,i)=>({...g,values:{'Receiving yards':i===0?'bad':i+20}}));
assert.equal(bridgeNflverseArchive({...archive,players:[{player_id:'nfl-123',games:malformed}]},now).status,'UNAVAILABLE');
console.log('Existing NFL archive bridge provenance tests passed');
