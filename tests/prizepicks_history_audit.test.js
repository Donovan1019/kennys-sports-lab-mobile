'use strict';
const assert=require('node:assert/strict');
const {auditHistory}=require('../scripts/prizepicks_history_audit');
const feed={status:'RAW_LINES_ONLY',lines:[{id:'1',league:'NBA',player:'A',market:'Points',line:12.5,period:'Full game',player_id:'p1'}]};
const result=auditHistory(feed,[]);
assert.equal(result.status,'UNAVAILABLE');assert.equal(result.coverage.unavailable,1);
assert.equal(result.rows[0].betEligible,false);assert.equal(result.rows[0].moreRate,null);
assert.equal(result.rows[0].last5,null);
const games=Array.from({length:15},(_,i)=>({eventId:'e'+i,playedAt:'2026-10-'+String(i+1).padStart(2,'0')+'T00:00:00Z',verified:true,value:i+1}));
const record={independentlyVerified:true,playerId:'p1',providerPlayerId:'p1',league:'NBA',market:'Points',period:'Full game',source:'independent',games};
const audit=auditHistory(feed,[record],Date.parse('2026-11-03T20:00:00Z'));
assert.equal(audit.status,'PARTIAL_HISTORY');
assert.equal(audit.rows[0].last5.sample,5);
assert.equal(audit.rows[0].last10.sample,10);
assert.equal(audit.rows[0].last15.sample,15);
assert.equal(audit.rows[0].last5.mean,13);
assert.equal(audit.rows[0].modelValidated,false);
assert.equal(audit.rows[0].betEligible,false);
console.log('PrizePicks history audit and chronological window checks passed');
