'use strict';
const assert=require('node:assert/strict');
const {runAudit,chooseVerifiedHistory,identityReadiness}=require('../scripts/prizepicks_history_automation');
const now=Date.parse('2026-11-03T20:00:00Z');
const feed={status:'RAW_LINES_ONLY',generated_at:'2026-11-03T19:50:00Z',lines:[{id:'x',league:'NBA',player:'Example',player_id:'pp-1',market:'Points',period:'Full game',line:15.5}]};
const games=Array.from({length:15},(_,i)=>({eventId:'e'+i,playedAt:'2026-10-'+String(i+1).padStart(2,'0')+'T00:00:00Z',verified:true,value:i+10}));
const history={schema_version:1,status:'VERIFIED_GAME_LOGS',source:'independent',generated_at:'2026-11-03T19:00:00Z',records:[{playerId:'hist-1',providerPlayerId:'hist-1',league:'NBA',market:'Points',period:'Full game',source:'independent',independentlyVerified:true,games}]};
const crosswalk=[{verified:true,league:'NBA',prizepicksPlayerId:'pp-1',historyPlayerId:'hist-1',historySource:'independent'}];
const good=runAudit(feed,history,crosswalk,now);
assert.equal(good.coverage.matched,1);assert.equal(good.rows[0].last5.sample,5);
assert.equal(good.betEligible,false);assert.equal(good.rows[0].betEligible,false);
assert.equal(runAudit(feed,null,null,now).status,'UNAVAILABLE');
assert.equal(runAudit({...feed,generated_at:'2026-11-03T18:00:00Z'},history,crosswalk,now).status,'UNAVAILABLE');
assert.equal(runAudit({...feed,generated_at:'2026-11-03T20:02:00Z'},history,crosswalk,now).status,'UNAVAILABLE');
const missingCrosswalk=runAudit(feed,history,[],now);
assert.equal(missingCrosswalk.status,'UNAVAILABLE');
assert.deepEqual(missingCrosswalk.coverage,{total:1,matched:0,unavailable:1,byLeague:{NBA:1}});
assert.equal(chooseVerifiedHistory(null,null,now),null);
assert.equal(chooseVerifiedHistory(history,null,now),history);
const archive={source:'nflverse-stats-player-week',independentlyVerified:true,fetched_at:'2026-11-03T19:00:00Z',players:[{player_id:'nfl-123',games:games.map(g=>({...g,verified:true,values:{'Receiving yards':g.value}}))}]};
assert.equal(chooseVerifiedHistory(null,archive,now).status,'VERIFIED_GAME_LOGS');
assert.equal(chooseVerifiedHistory({status:'UNAVAILABLE'},archive,now).status,'VERIFIED_GAME_LOGS');
assert.equal(chooseVerifiedHistory({...history,generated_at:'2026-01-01T00:00:00Z'},archive,now).status,'VERIFIED_GAME_LOGS');
assert.equal(chooseVerifiedHistory({status:'UNAVAILABLE'},null,now),null);
assert.equal(chooseVerifiedHistory(null,{...archive,independentlyVerified:false},now),null);
const fs=require('node:fs');
const script=fs.readFileSync(require.resolve('../scripts/prizepicks_history_automation'),'utf8');
assert.ok(script.includes("PRIZEPICKS_CROSSWALK_PATH||'feed/prizepicks_verified_crosswalk.json'"));
assert.match(script,/verifiedCrosswalk:/);
const readiness=identityReadiness(feed,history,crosswalk);
assert.equal(readiness.providerPlayers,1);
assert.deepEqual(readiness.byLeague.NBA,{sourceLines:1,providerPlayers:1,historicalPlayerMarketRecords:1,verifiedPlayerMappings:1});
assert.equal(identityReadiness(feed,null,[]).byLeague.NBA.historicalPlayerMarketRecords,0);
assert.equal(readiness.verifiedMappingsWithBothIdsPresent,1);
assert.equal(readiness.distinctProviderPlayersWithCandidateMappings,1);
assert.equal(readiness.automaticNameMatching,false);
assert.equal(readiness.conflictingProviderMappings,0);
assert.equal(readiness.conflictingHistoryMappings,0);
const duplicate=identityReadiness(feed,history,[...crosswalk,...crosswalk]);
assert.equal(duplicate.conflictingProviderMappings,1);
assert.equal(duplicate.conflictingHistoryMappings,1);
assert.equal(duplicate.distinctProviderPlayersWithCandidateMappings,0);
assert.equal(identityReadiness(feed,history,[]).verifiedMappingsWithBothIdsPresent,0);
console.log('Automated PrizePicks history audit fail-closed tests passed');
