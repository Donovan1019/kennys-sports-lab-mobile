'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const workflow=fs.readFileSync('.github/workflows/prizepicks-ingest.yml','utf8');
assert.match(workflow,/cron: '0 14,15,20,21 \* \* \*'/);
assert.match(workflow,/TZ=America\/New_York date \+%H/);
assert.match(workflow,/permissions:\s*\n\s*contents: write/);
assert.doesNotMatch(workflow,/contents:\s*\$\{\{/);
const gates=workflow.match(/if: github\.event_name != 'pull_request' && \(github\.event_name != 'workflow_run' \|\| github\.event\.workflow_run\.conclusion == 'success'\) && steps\.eastern\.outputs\.run == 'true'/g)||[];
const originalGates=workflow.match(/if: github\.event_name != 'pull_request' && steps\.eastern\.outputs\.run == 'true'/g)||[];
assert.equal(gates.length+originalGates.length,9,'independent NBA/NHL collection and identity diagnostics must retain Eastern gate');
assert.match(workflow,/Build identity candidate report for automated production diagnostics/);
assert.match(workflow,/id: provider\s*\n\s*continue-on-error: true/);
assert.match(workflow,/if: steps.provider.outcome == 'success' && github.event_name != 'pull_request'/);
assert.match(workflow,/if: always\(\) && github.event_name != 'pull_request' && steps.eastern.outputs.run == 'true'/);
assert.match(workflow,/No stale betting feed published/);
assert.match(workflow,/workflow_run:\s*\n\s*workflows: \['NFL Real Player Stats Ingestion'\]/);
assert.ok(workflow.includes("github.event.workflow_run.conclusion }}\" != 'success'"));
assert.ok(workflow.includes('Validate audit artifact and source provenance'));
assert.ok(workflow.includes('prizepicks-research-diagnostics'));
assert.ok(workflow.includes("a.inputs.nflArchive!=='FOUND'"));
console.log('PrizePicks schedule and publication gate tests passed');
