'use strict';
const assert=require('node:assert/strict');
const {collect,convertLog,seasonId,getJson}=require('../scripts/prizepicks_nhl_collector');
const now=Date.parse('2026-11-03T20:00:00Z');
assert.equal(seasonId(new Date(now)),'20262027');
const log=Array.from({length:15},(_,i)=>({gameId:100+i,gameDate:'2026-10-'+String(i+1).padStart(2,'0'),shots:3,goals:1,assists:1,points:2,blockedShots:0}));
assert.equal(convertLog(123,log,now).length,5);
const goalieLog=log.map(g=>({...g,saves:27,goalsAgainst:2}));
assert.equal(convertLog(123,goalieLog,now,'goalie').length,2);
assert.equal(convertLog(123,goalieLog,now,'goalie').find(x=>x.market==='Saves').games[0].value,27);
assert.equal(convertLog(123,log.slice(0,14),now).length,0);
assert.equal(convertLog(123,log.map(g=>({...g,shots:undefined})),now).some(r=>r.market==='Shots on Goal'),false);
const mock=async url=>({ok:true,json:async()=>url.includes('/roster/BOS/')?{forwards:[{id:123,firstName:{default:'Jane'},lastName:{default:'Example'}}]}:url.includes('/roster/')?{forwards:[]}:url.includes('/player/123/game-log/20262027/')?{gameLog:log}:{gameLog:[]}});
(async()=>{
 const feed={lines:[{league:'NHL',player:'Jane Example'}]};
 const result=await collect(feed,now,mock);
 assert.equal(result.status,'VERIFIED_GAME_LOGS');
 assert.equal(result.records.length,5);
 assert.equal(result.records[0].source,'api-web.nhle.com/v1');
 assert.equal(result.diagnostics.matchedRosterIds,1);
 const withProvider=await collect({lines:[{league:'NHL',player:'Jane Example',player_id:'pp-123'}]},now,mock);
 assert.deepEqual(withProvider.diagnostics.identityCandidates[0].nhlCandidateIds,['123']);
 assert.equal(withProvider.diagnostics.identityCandidates[0].status,'UNVERIFIED_NAME_CANDIDATE');
 assert.equal(result.diagnostics.gameLogFailures.length,0);
 const goalieFeed={lines:[{league:'NHL',player:'Sam Goalie'}]};
 const goalieMock=async url=>({ok:true,json:async()=>url.includes('/roster/BOS/')?{goalies:[{id:456,firstName:{default:'Sam'},lastName:{default:'Goalie'}}]}:url.includes('/roster/')?{goalies:[]}:url.includes('/player/456/game-log/20262027/')?{gameLog:goalieLog}:{gameLog:[]}});
 const goalieResult=await collect(goalieFeed,now,goalieMock);
 assert.equal(goalieResult.records.length,2);
 assert.equal(goalieResult.records.find(x=>x.market==='Saves').games.length,15);
 const collisionMock=async url=>({ok:true,json:async()=>url.includes('/roster/BOS/')?{forwards:[{id:123,firstName:{default:'Jane'},lastName:{default:'Example'}}]}:url.includes('/roster/TOR/')?{forwards:[{id:999,firstName:{default:'Jane'},lastName:{default:'Example'}}]}:url.includes('/roster/')?{forwards:[]}:{gameLog:log}});
 const collision=await collect(feed,now,collisionMock);
 assert.equal(collision.status,'UNAVAILABLE');
 assert.equal(collision.records.length,0);
 assert.deepEqual(collision.diagnostics.ambiguousRosterNames,['janeexample']);
 const partialMock=async url=>url.includes('/roster/TOR/')?{ok:false,status:503,json:async()=>({})}:mock(url);
 const partial=await collect(feed,now,partialMock);
 assert.equal(partial.status,'UNAVAILABLE');
 assert.equal(partial.records.length,0);
 assert.ok(partial.diagnostics.rosterFailures.some(x=>x.startsWith('TOR:')));
 let active=0,maxActive=0;
 const concurrentMock=async url=>{active++;maxActive=Math.max(maxActive,active);await new Promise(resolve=>setTimeout(resolve,2));const response=await mock(url);active--;return response};
 const parallel=await collect(feed,now,concurrentMock);
 assert.equal(parallel.status,'VERIFIED_GAME_LOGS');
 assert.ok(maxActive>1&&maxActive<=6,'network concurrency must be bounded');
 let attempts=0;
 const retried=await getJson('https://api-web.nhle.com/test',async()=>{attempts++;return attempts<3?{ok:false,status:429}:{ok:true,json:async()=>({ready:true})}},async()=>{});
 assert.equal(attempts,3);
 assert.equal(retried.ready,true);
 let notFoundAttempts=0;
 await assert.rejects(()=>getJson('https://api-web.nhle.com/test',async()=>{notFoundAttempts++;return {ok:false,status:404}},async()=>{}),/NHL HTTP 404/);
 assert.equal(notFoundAttempts,1);
 const unavailable=await collect({lines:[{league:'NHL',player:'Unknown'}]},now,mock);
 assert.equal(unavailable.status,'UNAVAILABLE');
 assert.equal(unavailable.diagnostics.reason,'no unambiguous NHL roster matches');
 assert.equal(result.diagnostics.verifiedMarketRecords,5);
 console.log('Official NHL historical collector tests passed');
})().catch(e=>{console.error(e);process.exitCode=1});
