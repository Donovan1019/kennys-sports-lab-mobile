'use strict';
const assert=require('node:assert/strict');
const {impliedProbability,decimalOdds,noVig,expectedValue,kellyFraction}=require('../ufc_market_math');
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-10,`${a} vs ${b}`);
near(impliedProbability(-150),.6);
near(impliedProbability(200),1/3);
near(decimalOdds(-150),1+100/150);
near(decimalOdds(200),3);
assert.equal(impliedProbability(-99),null);
assert.equal(impliedProbability(NaN),null);
const fair=noVig(-110,-110);
near(fair.a,.5);near(fair.b,.5);assert.ok(fair.overround>0);
assert.equal(noVig(-500,-500),null);
near(expectedValue(.5,100),0);
near(expectedValue(.6,100),.2);
near(expectedValue(.4,100),-.2);
near(kellyFraction(.5,100),0);
near(kellyFraction(.6,100),.2);
assert.equal(expectedValue(1.2,100),null);
assert.equal(kellyFraction(-.1,100),null);
console.log('UFC market EV math PASS');
