#!/usr/bin/env python3
"""Paired, chronological UFC camp-feature ablation audit.
Accepts predictions generated by TWO frozen models on identical held-out fights.
Never manufactures probabilities, and never authorizes betting.
"""
import argparse
import datetime as dt
import json
import math
import random
from pathlib import Path

def instant(value):
    x=dt.datetime.fromisoformat(value.replace("Z","+00:00"))
    if x.tzinfo is None: raise ValueError("Timezone required")
    return x.astimezone(dt.timezone.utc)

def audit(rows,iterations=2000,min_pairs=100):
    if not isinstance(rows,list):raise ValueError("Expected paired predictions list")
    if not isinstance(iterations,int) or not 100<=iterations<=10000:raise ValueError("Invalid bootstrap iterations")
    if not isinstance(min_pairs,int) or min_pairs<1:raise ValueError("Invalid minimum pairs")
    seen=set();pairs=[];rejected=[]
    for r in rows:
        fid=r.get("fight_id") if isinstance(r,dict) else None
        try:
            if not isinstance(fid,str) or not fid or fid in seen:raise ValueError("Missing or duplicate fight ID")
            seen.add(fid)
            start=instant(r["start_time"]);base_at=instant(r["baseline_generated_at"])
            camp_at=instant(r["camp_generated_at"])
            verified_at=instant(r["camp_verified_at"])
            if not (base_at<start and camp_at<start and verified_at<=camp_at):
                raise ValueError("Post-start or future-sourced features")
            if r.get("holdout_verified") is not True or r.get("camp_source_verified") is not True:
                raise ValueError("Unverified holdout or camp source")
            if r.get("baseline_model_version")==r.get("camp_model_version") or not all((r.get("baseline_model_version"),r.get("camp_model_version"))):
                raise ValueError("Distinct frozen model versions required")
            y=r["red_won"]
            if type(y) is not bool:raise ValueError("Invalid outcome")
            p0,p1=r["baseline_red_probability"],r["camp_red_probability"]
            if any(type(p) not in (int,float) or not math.isfinite(p) or not 0<p<1 for p in (p0,p1)):
                raise ValueError("Invalid probabilities")
            outcome=int(y)
            pairs.append(((p0-outcome)**2,(p1-outcome)**2))
        except (KeyError,ValueError,TypeError,AttributeError) as exc:
            rejected.append({"fight_id":fid,"reason":str(exc)})
    n=len(pairs)
    if not n:
        return {"paired_fights":0,"rejected":rejected,"status":"INSUFFICIENT_SAMPLE","bet_eligible":False,
                "baseline_brier":None,"camp_brier":None,"improvement":None,"bootstrap_ci_95":None}
    baseline=sum(a for a,b in pairs)/n
    camp=sum(b for a,b in pairs)/n
    improvements=[a-b for a,b in pairs]
    rng=random.Random(20261023)
    samples=sorted(sum(improvements[rng.randrange(n)] for _ in range(n))/n for _ in range(iterations))
    ci=[samples[int(.025*(iterations-1))],samples[int(.975*(iterations-1))]]
    return {"paired_fights":n,"rejected":rejected,"baseline_brier":baseline,"camp_brier":camp,
            "improvement":baseline-camp,"bootstrap_ci_95":ci,
            "status":"INSUFFICIENT_SAMPLE" if n<min_pairs else ("POSSIBLE_IMPROVEMENT_REQUIRES_INDEPENDENT_REVIEW" if ci[0]>0 else "NO_ROBUST_IMPROVEMENT"),
            "bet_eligible":False,"limitations":["Paired bootstrap assumes independent fights; gym/fighter clustering requires block bootstrap",
                "Both model versions and hyperparameters must be frozen before the holdout",
                "No proof of causal gym advantage; selection bias and correlated fighters remain",
                "No odds, calibration acceptance, or live betting authorization"]}
def main():
    p=argparse.ArgumentParser()
    p.add_argument("--input",required=True);p.add_argument("--output",default="backtests/reports/ufc_camp_ablation.json")
    a=p.parse_args()
    report=audit(json.loads(Path(a.input).read_text())["paired_predictions"])
    out=Path(a.output);out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(json.dumps(report,indent=2)+"\n")
    print(report["status"],report["paired_fights"])
if __name__=="__main__":main()
