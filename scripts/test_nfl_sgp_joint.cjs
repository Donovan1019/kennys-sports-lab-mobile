const fs=require('fs'),vm=require('vm'),assert=require('assert');
const ctx={window:{}};vm.runInNewContext(fs.readFileSync('nfl_sgp_joint_bootstrap.js','utf8'),ctx);
const joint=ctx.window.KSLSGPJoint.joint;
const make=(name,offset)=>({name,games:Array.from({length:8},(_,i)=>({season:2026,week:i+1,season_type:'REG',game_id:'2026_'+i+'_TB_CHI',values:{'Passing yards':180+offset+i*12,'Receiving yards':40+offset+i*5}}))});
const stats={source:'nflverse-stats-player-week',players:[make('Test QB',0),make('Test WR',5)]};
const legs=[{player:'Test QB',market:'player_pass_yds',point:210,selection:'Over'},{player:'Test WR',market:'player_reception_yds',point:55,selection:'Over'}];
const good=joint(stats,legs,{trials:2000});
assert.strictEqual(good.status,'EXPERIMENTAL');assert.strictEqual(good.paired_events,8);
assert.strictEqual(good.trials,2000);assert.strictEqual(good.betting_eligible,false);
assert.strictEqual(good.validated_same_game,false);assert.strictEqual(good.official_sgp_price_available,false);
assert(good.joint_rate>=0&&good.joint_rate<=1);
assert.strictEqual(joint(stats,legs,{trials:2000}).joint_rate,good.joint_rate);
const mismatched=JSON.parse(JSON.stringify(stats));mismatched.players[1].games.forEach((g,i)=>g.game_id='different_'+i);
assert.strictEqual(joint(mismatched,legs).status,'BLOCKED');
assert.strictEqual(joint(stats,[legs[0],legs[0]]).status,'BLOCKED');
assert.strictEqual(joint(stats,[{...legs[0],player:'Unknown'},legs[1]]).status,'BLOCKED');
assert.strictEqual(joint(stats,[{...legs[0],point:null},legs[1]]).status,'BLOCKED');
assert.strictEqual(joint(stats,[{...legs[0],market:'fake'},legs[1]]).status,'BLOCKED');
const insufficient=JSON.parse(JSON.stringify(stats));insufficient.players.forEach(p=>p.games=p.games.slice(0,4));
assert.strictEqual(joint(insufficient,legs).status,'BLOCKED');
console.log('PASS NFL SGP joint integrity');
